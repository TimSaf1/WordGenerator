const Articles = (() => {
  // Ищем лучший тематический раздел: сравниваем леммоподобные префиксы
  // термина с тегами хабов. Возвращаем {name, url, hub}.
  function pick(domainKey, term) {
    const sites = ARTICLE_SITES[domainKey] || [];
    const t = (" " + term.toLowerCase() + " ").normalize("NFKD");
    let best = null;         // {site, hub, score}
    for (const site of sites) {
      for (const [hub, tags] of (site.hubs || [])) {
        for (const tag of tags) {
          // сравнение по префиксу (5 симв.) — грубая «лемматизация»
          const p = tag.slice(0, Math.max(4, tag.length - 2));
          if (p.length >= 4 && t.includes(p)) {
            const score = p.length;
            if (!best || score > best.score) best = { site, hub, score };
          }
        }
      }
    }
    if (best) {
      return { name: `${best.site.name} → ${best.hub}`, url: best.site.url };
    }
    // не нашли тег — случайный раздел случайного сайта сферы
    if (sites.length) {
      const site = sites[Math.floor(Math.random() * sites.length)];
      const hubs = site.hubs || [];
      if (hubs.length) {
        const [hub] = hubs[Math.floor(Math.random() * hubs.length)];
        return { name: `${site.name} → ${hub}`, url: site.url };
      }
      return { name: site.name, url: site.url };
    }
    const fb = FALLBACK_ARTICLES[Math.floor(Math.random() * FALLBACK_ARTICLES.length)];
    return fb;
  }
  return { pick };
})();
